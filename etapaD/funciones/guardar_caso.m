function guardar_caso(dirRes, nombre, R)
%GUARDAR_CASO Serie por cuadro de un caso MIL (dos ejes) en D_caso_<nombre>.csv.
% x_plato se interpola del registro continuo a los instantes de captura.
xp = interp1(R.t, R.x, R.k_tcap);
thp = interp1(R.t, R.th, R.k_tcap);
escribir_csv(fullfile(dirRes, ['D_caso_' nombre '.csv']), ...
    {'t_cap_s','t_calc_s','r_x_mm','r_y_mm','y_x_mm','y_y_mm','xh_x_mm','xh_y_mm', ...
     'vh_x_mm_s','vh_y_mm_s','thcmd_x_deg','thcmd_y_deg','u_x_deg','u_y_deg', ...
     'sat_x','sat_y','I_x_deg','I_y_deg','x_plato_mm','y_plato_mm','thx_plato_deg','thy_plato_deg'}, ...
    [R.k_tcap R.k_t R.k_r R.k_y R.k_xh R.k_vh rad2deg(R.k_th) rad2deg(R.k_u) ...
     double(R.k_sat) rad2deg(R.k_I) xp rad2deg(thp)]);
end
