%% Validacion comparativa del modelo MIL del TCLab
% Compara tres implementaciones del PI SIMC/IMC en una sola simulacion:
%   1. PI ideal, sin saturacion.
%   2. PI con saturacion externa, sin anti-windup.
%   3. PI con saturacion interna y anti-windup por clamping.
%
% Antes de ejecutar este script, el modelo de Simulink debe generar las
% siguientes variables mediante bloques To Workspace en formato Timeseries:
%
%   T1_ideal_sim       Qcmd_ideal_sim
%   T1_sinAW_sim       Qcmd_sinAW_sim       Q1_sinAW_sim
%   T1_conAW_sim                              Q1_conAW_sim
%
% Tambien deben estar disponibles T_ref, T_amb, Q_min, Q_max, T_max,
% ts_max y OS_max, definidos en A8_init_TCLab_SIMC.m.

%% Comprobacion de variables necesarias

variables_necesarias = { ...
    'T1_ideal_sim', ...
    'Qcmd_ideal_sim', ...
    'T1_sinAW_sim', ...
    'Qcmd_sinAW_sim', ...
    'Q1_sinAW_sim', ...
    'T1_conAW_sim', ...
    'Q1_conAW_sim', ...
    'T_ref', ...
    'T_amb', ...
    'Q_min', ...
    'Q_max', ...
    'T_max', ...
    'ts_max', ...
    'OS_max'};

variables_faltantes = variables_necesarias( ...
    ~cellfun(@(nombre) evalin('base', ...
    sprintf("exist('%s','var')", nombre)), variables_necesarias));

if ~isempty(variables_faltantes)
    error('Faltan las siguientes variables: %s', ...
        strjoin(variables_faltantes, ', '));
end

%% Calculo de metricas

% En el caso ideal, la potencia solicitada y la aplicada son iguales.
metricas_ideal = calcularMetricasSimulink( ...
    T1_ideal_sim, ...
    Qcmd_ideal_sim, ...
    Qcmd_ideal_sim, ...
    T_ref, T_amb, Q_min, Q_max);

metricas_sinAW = calcularMetricasSimulink( ...
    T1_sinAW_sim, ...
    Qcmd_sinAW_sim, ...
    Q1_sinAW_sim, ...
    T_ref, T_amb, Q_min, Q_max);

% El bloque Discrete PID Controller con limites internos entrega la salida
% ya saturada. Por eso Qcmd no esta disponible en este caso y se pasa [].
metricas_conAW = calcularMetricasSimulink( ...
    T1_conAW_sim, ...
    [], ...
    Q1_conAW_sim, ...
    T_ref, T_amb, Q_min, Q_max);

%% Presentacion de resultados

% Se conservan los resultados completos en una tabla para su uso posterior.
Caso = [ ...
    "PI ideal"; ...
    "Saturación sin AW"; ...
    "Saturación con AW"];

TiempoSubida_s = [ ...
    metricas_ideal.RiseTime; ...
    metricas_sinAW.RiseTime; ...
    metricas_conAW.RiseTime];

TiempoEstablecimiento_s = [ ...
    metricas_ideal.SettlingTime; ...
    metricas_sinAW.SettlingTime; ...
    metricas_conAW.SettlingTime];

Sobreimpulso_pct = [ ...
    metricas_ideal.Overshoot; ...
    metricas_sinAW.Overshoot; ...
    metricas_conAW.Overshoot];

ErrorEstacionario_degC = [ ...
    metricas_ideal.ErrorEstacionario; ...
    metricas_sinAW.ErrorEstacionario; ...
    metricas_conAW.ErrorEstacionario];

TemperaturaMaxima_degC = [ ...
    metricas_ideal.TemperaturaMaxima; ...
    metricas_sinAW.TemperaturaMaxima; ...
    metricas_conAW.TemperaturaMaxima];

PotenciaMinima_pct = [ ...
    metricas_ideal.PotenciaMinima; ...
    metricas_sinAW.PotenciaMinima; ...
    metricas_conAW.PotenciaMinima];

PotenciaMaxima_pct = [ ...
    metricas_ideal.PotenciaMaxima; ...
    metricas_sinAW.PotenciaMaxima; ...
    metricas_conAW.PotenciaMaxima];

TiempoQcmdFueraRango_s = [ ...
    metricas_ideal.TiempoQcmdFueraRango; ...
    metricas_sinAW.TiempoQcmdFueraRango; ...
    metricas_conAW.TiempoQcmdFueraRango];

resultados_SIMC = table( ...
    Caso, ...
    TiempoSubida_s, ...
    TiempoEstablecimiento_s, ...
    Sobreimpulso_pct, ...
    ErrorEstacionario_degC, ...
    TemperaturaMaxima_degC, ...
    PotenciaMinima_pct, ...
    PotenciaMaxima_pct, ...
    TiempoQcmdFueraRango_s);

% Tabla 1: desempeno dinamico
fprintf('\nCOMPARACION DE DESEMPENO\n');
fprintf('=========================================================================\n');
fprintf('%-24s %10s %10s %10s %12s\n', ...
    'Caso', 'tr [s]', 'ts [s]', 'Mp [%]', 'ess [degC]');
fprintf('-------------------------------------------------------------------------\n');

for k = 1:height(resultados_SIMC)
    fprintf('%-24s %10.2f %10.2f %10.2f %12.4f\n', ...
        resultados_SIMC.Caso(k), ...
        resultados_SIMC.TiempoSubida_s(k), ...
        resultados_SIMC.TiempoEstablecimiento_s(k), ...
        resultados_SIMC.Sobreimpulso_pct(k), ...
        resultados_SIMC.ErrorEstacionario_degC(k));
end

% Tabla 2: restricciones fisicas
fprintf('\nRESTRICCIONES FÍSICAS\n');
fprintf('===============================================================================\n');
fprintf('%-24s %11s %10s %10s %15s\n', ...
    'Caso', 'Tmax [degC]', 'Qmin [%]', 'Qmax [%]', 'Qcmd fuera [s]');
fprintf('-------------------------------------------------------------------------------\n');

for k = 1:height(resultados_SIMC)
    if isnan(resultados_SIMC.TiempoQcmdFueraRango_s(k))
        tiempo_fuera = '--';
    else
        tiempo_fuera = sprintf('%.0f', ...
            resultados_SIMC.TiempoQcmdFueraRango_s(k));
    end

    fprintf('%-24s %11.2f %10.2f %10.2f %15s\n', ...
        resultados_SIMC.Caso(k), ...
        resultados_SIMC.TemperaturaMaxima_degC(k), ...
        resultados_SIMC.PotenciaMinima_pct(k), ...
        resultados_SIMC.PotenciaMaxima_pct(k), ...
        tiempo_fuera);
end

%% Verificacion de requisitos del controlador con anti-windup

cumple_ts = metricas_conAW.SettlingTime <= ts_max;
cumple_OS = metricas_conAW.Overshoot <= OS_max;
cumple_Q = metricas_conAW.PotenciaMinima >= Q_min && ...
    metricas_conAW.PotenciaMaxima <= Q_max;
cumple_T = metricas_conAW.TemperaturaMaxima <= T_max;

% Se conserva tambien una tabla logica en el workspace.
cumplimiento_conAW = table( ...
    cumple_ts, cumple_OS, cumple_Q, cumple_T, ...
    'VariableNames', { ...
        'CumpleTiempoEstablecimiento', ...
        'CumpleSobreimpulso', ...
        'CumpleLimitesPotencia', ...
        'CumpleLimiteTemperatura'});

fprintf('\nCUMPLIMIENTO: SATURACION CON ANTI-WINDUP\n');
fprintf('=============================================================\n');
fprintf('Tiempo de establecimiento <= %.0f s   %s\n', ...
    ts_max, textoCumplimiento(cumple_ts));
fprintf('Sobreimpulso <= %.0f %%                   %s\n', ...
    OS_max, textoCumplimiento(cumple_OS));
fprintf('Potencia entre %.0f y %.0f %%             %s\n', ...
    Q_min, Q_max, textoCumplimiento(cumple_Q));
fprintf('Temperatura <= %.0f degC                %s\n', ...
    T_max, textoCumplimiento(cumple_T));

fprintf(['\nNota: -- indica que Qcmd no esta disponible para el caso con ', ...
    'anti-windup porque \n el bloque PID no expone la señal interna ', ...
    'anterior a la saturación.\n']);

