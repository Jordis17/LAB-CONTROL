%% Funciones locales

function metricas = calcularMetricasSimulink( ...
    T1_ts, Qcmd_ts, Q1_ts, T_ref, T_amb, Q_min, Q_max)

    [t_T1, T1] = extraerTimeseries(T1_ts, 'temperatura');
    [~, Q1] = extraerTimeseries(Q1_ts, 'potencia aplicada');

    DeltaT1 = T1 - T_amb;
    DeltaT_ref = T_ref - T_amb;

    info = stepinfo( ...
        DeltaT1, ...
        t_T1, ...
        DeltaT_ref, ...
        'SettlingTimeThreshold', 0.02);

    indices_finales = t_T1 >= t_T1(end) - 60;
    error_estacionario = T_ref - mean(T1(indices_finales));

    if isempty(Qcmd_ts)
        tiempo_Qcmd_fuera_rango = NaN;
    else
        [t_Qcmd, Qcmd] = extraerTimeseries(Qcmd_ts, 'comando PI');

        if numel(t_Qcmd) < 2
            tiempo_Qcmd_fuera_rango = 0;
        else
            fuera_rango = Qcmd > Q_max | Qcmd < Q_min;
            tiempo_Qcmd_fuera_rango = sum( ...
                diff(t_Qcmd).*double(fuera_rango(1:end-1)));
        end
    end

    metricas.RiseTime = info.RiseTime;
    metricas.SettlingTime = info.SettlingTime;
    metricas.Overshoot = info.Overshoot;
    metricas.ErrorEstacionario = error_estacionario;
    metricas.TemperaturaMaxima = max(T1);
    metricas.PotenciaMinima = min(Q1);
    metricas.PotenciaMaxima = max(Q1);
    metricas.TiempoQcmdFueraRango = tiempo_Qcmd_fuera_rango;
end


function texto = textoCumplimiento(condicion)

    if condicion
        texto = 'Cumple';
    else
        texto = 'No cumple';
    end
end

function [t, datos] = extraerTimeseries(senal, nombre)

    if ~isa(senal, 'timeseries')
        error('%s debe estar guardada en formato Timeseries.', nombre);
    end

    t = senal.Time(:);
    datos = squeeze(senal.Data);

    if ~isvector(datos)
        error('%s debe contener una unica senal.', nombre);
    end

    datos = datos(:);

    if numel(t) ~= numel(datos)
        error('El tiempo y los datos de %s tienen longitudes distintas.', ...
            nombre);
    end
end
